/******************************************************************************
	???????????????????????
	????????rotation 0, 90, 180, 270
	???????  ??
******************************************************************************/
HAL_StatusTypeDef LCD_SetRotation(uint16_t rotation)
{
    uint8_t command = 0x36U; /* MADCTL */
    uint8_t madctl;
    uint8_t offset_x = 0U;
    uint8_t offset_y = 0U;
    HAL_StatusTypeDef status;

    switch (rotation)
    {
        case 0U:
            madctl = 0x00U;
            break;
        case 90U:
            madctl = 0x70U;
            break;
        case 180U:
            madctl = 0xC0U;
            offset_y = 80U;
            break;
        case 270U:
            madctl = 0xA0U;
            offset_x = 80U;
            break;
        default:
            return HAL_ERROR;
    }

    LCD_DC_Clr();
    status = HAL_SPI_Transmit(&hspi2, &command, 1U, LCD_ROTATION_SPI_TIMEOUT_MS);
    LCD_DC_Set();
    if (status != HAL_OK)
    {
        return status;
    }

    status = HAL_SPI_Transmit(&hspi2, &madctl, 1U, LCD_ROTATION_SPI_TIMEOUT_MS);
    if (status == HAL_OK)
    {
        OFFSET_X = offset_x;
        OFFSET_Y = offset_y;
        LCD_ROTATION = rotation;
    }
    return status;
}

